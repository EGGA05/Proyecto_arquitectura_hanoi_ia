# Torres de Hanoi - version optimizada al maximo.
# Idea: los M = 10 discos mas chicos siempre hacen la misma secuencia de 2^M - 1
# movimientos, asi que esa secuencia se escribe en linea recta (solo 2 sw por
# movimiento, sin saltos, sin comparaciones, sin actualizar apuntadores). Solo los
# discos > M se mueven con logica general (una vez cada 2^M - 1 movimientos).
# Si n < M se salta directo a la parte final del bloque recto que mueve n discos.
# Layout igual al original: filas de 32 bytes, Torre 1 en +0, Torre 2 en +4, Torre 3 en +8.
# sp queda apuntando a la base del canvas y se usa como base (el programa no usa pila).
.text
main:
	addi	s0, zero, 8		#s0 - numero de discos

	slli	t1, s0, 2
	sub	s4, sp, t1		#s4 = sp - 4n = (base + 32n): primer espacio libre de Torre 1
	slli	t3, s0, 5
	sub	sp, s4, t3		#sp = sp - 36n: base del canvas (mismo tamano que el original)
	bge	zero, s0, fin_ini	#n <= 0: nada que hacer

	sw	sp, -32(sp)		#fila centinela debajo del canvas: una torre vacia
	sw	sp, -28(sp)		#"tiene" un disco enorme (el valor de sp, mayor que
	sw	sp, -24(sp)		#cualquier disco), asi no hay casos especiales

	#registros con el valor de cada disco chico (sw necesita el valor en un registro)
	addi	a0, zero, 1
	addi	a1, zero, 2
	addi	a2, zero, 3
	addi	a3, zero, 4
	addi	a4, zero, 5
	addi	a5, zero, 6
	addi	a6, zero, 7
	addi	a7, zero, 8
	addi	s7, zero, 9
	addi	s8, zero, 10

	andi	t2, s0, 1		#t2 - paridad de n (s8 = M = 10 sirve como limite)
	blt	s0, s8, init_corto
	beq	s0, s8, init_tabla
	add	t1, sp, zero		#discos > M con loop (s0 baja hasta M)
init_loop:
	sw	s0, 0(t1)
	addi	s0, s0, -1
	addi	t1, t1, 32
	bne	s0, s8, init_loop
init_tabla:				#disco k va en s4 - 32k
	sw	s8, -320(s4)
	sw	s7, -288(s4)
	sw	a7, -256(s4)
	sw	a6, -224(s4)
	sw	a5, -192(s4)
	sw	a4, -160(s4)
	sw	a3, -128(s4)
	sw	a2, -96(s4)
	sw	a1, -64(s4)
	sw	a0, -32(s4)
init_tabla_fin:
	blt	s0, s8, corto

	#---- n >= M: el bloque de M discos va primero a T3 si (n-M) es par, si no a T2 ----
	beq	t2, zero, grande_par
					#n impar: arranca en la copia 2 para que el fin caiga siempre en la copia 0
	addi	s6, s4, -320		#U = Torre 1 (s6, con el desfase que espera la copia 2)
	addi	s4, sp, 324		#V = Torre 2 (s4, con desfase)
	addi	s5, sp, 8		#W = Torre 3
	jal	zero, b2

fin_ini:
	jal	zero, end		#(los branch solo alcanzan +-4 KB, jal alcanza +-1 MB)

init_corto:				#n < M: entrar a la tabla en el disco n
	la	t0, init_tabla_fin
	slli	t1, s0, 2
	sub	t0, t0, t1
	jalr	zero, 0(t0)

	#---- n < M: se ejecuta solo el final del bloque recto (mueve n discos) ----
	# Apuntadores "virtuales": como si los discos n+1..M ya estuvieran en V.
corto:
	addi	s5, s4, -312		#V = Torre 3 virtual: base3 - 32(M - n)
	bne	t2, zero, corto_impar
	addi	s4, sp, 320		#(M-n) par: U = Torre 1
	addi	s6, sp, 4		#           W = Torre 2
	jal	zero, corto_salto
corto_impar:
	addi	s4, sp, 324		#(M-n) impar: U = Torre 2
	add	s6, sp, zero		#             W = Torre 1
corto_salto:				#entrar 2*(2^n - 1) instrucciones antes del fin del bloque 0
	la	t0, b0_fin8		#b0_fin8 = fin del bloque + 8 bytes
	addi	t1, zero, 8
	sll	t1, t1, s0		#8 * 2^n
	sub	t0, t0, t1
	jalr	zero, 0(t0)

grande_par:				#n par: U = Torre 1 (s4), V = Torre 3, W = Torre 2
